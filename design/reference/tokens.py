def main() -> int:
    data = generate()
    text = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        ok = current == text
        print("TOKENS CURRENT" if ok else "TOKENS STALE: run python3 design/reference/tokens.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['colour'])} colour tokens, {len(data['type']['latin']['narrow'])} Latin type tokens")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
